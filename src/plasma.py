if (_pap / "index.theme").exists() and icon_theme_exists("Papirus-Dark"):
    import configparser
    T = HOME / ".local/share/icons/Papirus-Nocturne"
    dirs = []
    for d in sorted(_pap.glob("*/places")):
        rel = str(d.relative_to(_pap))
        n = 0
        for f in d.iterdir():
            target = Path(f.resolve()).name if f.is_symlink() else f.name
            teal = None
            if "-teal" in f.name:
                teal, name = f, f.name.replace("-teal", "")
            elif "-blue" in target and (d / target.replace("-blue", "-teal")).exists():
                teal, name = d / target.replace("-blue", "-teal"), f.name
            if teal:
                (T / rel).mkdir(parents=True, exist_ok=True)
                link = T / rel / name
                if link.is_symlink() or link.exists():
                    link.unlink()
                link.symlink_to(teal)
                n += 1
        if n:
            dirs.append(rel)
    src_idx = configparser.RawConfigParser(); src_idx.optionxform = str
    src_idx.read(_pap / "index.theme")
    lines = ["[Icon Theme]", "Name=Papirus-Nocturne", "Comment=Papirus-Dark with teal folders (Nocturne)",
             "Inherits=Papirus-Dark,breeze-dark,hicolor", "Directories=" + ",".join(dirs), ""]
    for d in dirs:
        lines += [f"[{d}]"] + [f"{k}={v}" for k, v in src_idx[d].items()] + [""]
    write(".local/share/icons/Papirus-Nocturne/index.theme", "\n".join(lines))
    ICONS = "Papirus-Nocturne"
