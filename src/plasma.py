def a(h, alpha):
    """#rrggbb + alpha(0-1) -> QML #AARRGGBB"""
    return f"#{round(alpha * 255):02x}{h[1:]}"


def kw(file, group, key, value):
    if not HAS_KDE:
        return
    track(f".config/{file}")
    groups = []
    for g in group if isinstance(group, list) else [group]:
        groups += ["--group", g]
    subprocess.run(["kwriteconfig6", "--file", file, *groups, "--key", key, str(value)], check=True)


def icon_theme_exists(name):
    dirs = [HOME / ".local/share/icons", HOME / ".icons", Path("/usr/share/icons"), Path("/usr/local/share/icons")]
