# ═══════════════════════════ fastfetch ═══════════════════════════
# Custom logo: the Nocturne crescent rasterised into truecolor half-block characters
LOGO_PX = 34                       # 34×34 px -> 34 columns × 17 rows
ff_logo = '{ "type": "small", "color": { "1": "%s", "2": "%s" }, "padding": { "top": 1, "right": 3 } }' % (
    sgr(C["mint"]), sgr(C["violet"]))
with tempfile.TemporaryDirectory() as _t:
    _svg = Path(_t) / "logo.svg"
    _svg.write_text(LOGO)
    px = pixels(_svg, LOGO_PX)
if px:
    _bg = tuple(int(C["mantle"][i:i + 2], 16) for i in (1, 3, 5))

    def _blend(p):
        """Anti-alias: mix semi-transparent edge pixels into the terminal background."""
        a = p[3] / 255
        return tuple(round(p[i] * a + _bg[i] * (1 - a)) for i in range(3))

    def _cell(top, bot):
        on = lambda p: p[3] > 24
        t, b = _blend(top), _blend(bot)
        if on(top) and on(bot):
            return f"\x1b[38;2;{t[0]};{t[1]};{t[2]}m\x1b[48;2;{b[0]};{b[1]};{b[2]}m▀\x1b[0m"
        if on(top):
            return f"\x1b[38;2;{t[0]};{t[1]};{t[2]}m▀\x1b[0m"
        if on(bot):
            return f"\x1b[38;2;{b[0]};{b[1]};{b[2]}m▄\x1b[0m"
        return " "
    rows = ["".join(_cell(px[y][x], px[y + 1][x]) for x in range(LOGO_PX)) for y in range(0, LOGO_PX, 2)]
    write(".config/fastfetch/nocturne-logo.txt", "\n".join(rows) + "\n")
    ff_logo = ('{ "type": "file-raw", "source": "~/.config/fastfetch/nocturne-logo.txt", '
               f'"width": {LOGO_PX}, "height": {LOGO_PX // 2}, '
               '"padding": { "top": 0, "left": 1, "right": 4 } }')

