# ═══════════════════════════ bat (also used by delta) ═══════════════════════════
def scope(name, sel, fg=None, style=None, bg=None):
    s = "".join(f"<key>{k}</key><string>{v}</string>" for k, v in
                (("foreground", fg), ("background", bg), ("fontStyle", style)) if v)
    return f"<dict><key>name</key><string>{name}</string><key>scope</key><string>{sel}</string>" \
           f"<key>settings</key><dict>{s}</dict></dict>"


