def a(h, alpha):
    return f"#{round(alpha * 255):02x}{h[1:]}"


def icon(name, body, color=C["text"]):
    write(f"{OUT}/icons/{name}.svg",
          f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{color}" '
          f'stroke-width="2" stroke-linecap="round" stroke-linejoin="round">{body}</svg>\n')


icon("power", '<path d="M12 3v8"/><path d="M6.3 6.8a8 8 0 1 0 11.4 0"/>')
icon("reboot", '<path d="M20 12a8 8 0 1 1-2.3-5.7"/><path d="M20 4v5h-5"/>')
icon("sleep", '<path d="M20 14.5A8 8 0 0 1 9.5 4a8 8 0 1 0 10.5 10.5z"/>')
icon("arrow", '<path d="M5 12h14"/><path d="M13 6l6 6-6 6"/>', C["on_mint"])
icon("left", '<path d="M15 6l-6 6 6 6"/>', C["subtext"])
icon("right", '<path d="M9 6l6 6-6 6"/>', C["subtext"])
icon("session", '<rect x="3" y="4" width="18" height="13" rx="2"/><path d="M8 21h8"/><path d="M12 17v4"/>', C["subtext"])
icon("lock", '<rect x="5" y="11" width="14" height="10" rx="2"/><path d="M8 11V7a4 4 0 0 1 8 0v4"/>', C["muted"])

