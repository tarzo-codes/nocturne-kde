"""Nocturne Starship prompt (24-bit; needs ble.sh >= 0.4 when ble.sh is used).

Layout
   ╭ os ╮╭  dir ╮╭  branch !2 ?1 ╮ ····················  3.12   4s  ╭ 17:22 ╮
  ❯
Finished prompts collapse to a single `❯` (transient prompt, set in ~/.bashrc).
"""
from palette import P, write

L, R = "", ""          # rounded pill caps
ICON = {
    "dir": "", "branch": "", "clock": "", "hourglass": "",
    "py": "", "node": "", "rust": "", "go": "", "java": "",
    "php": "", "c": "", "cpp": "", "lua": "", "docker": "",
    "jobs": "", "noexec": "", "linux": "", "arch": "\U000f08c7",
    "lock": "\U000f033e", "sudo": "\U000f030b", "pkg": "\U000f03d7", "bun": "",
    "deno": "", "kotlin": "",
}
I = ICON

palette = "\n".join(f'{k:<9}= "{P[k]}"' for k in
                    ["crust", "mantle", "surface", "surface2", "border", "text", "subtext", "muted",
                     "mint", "on_mint", "mint_tint", "violet_tint", "violet", "blue", "pink", "red", "orange", "yellow", "green"])


def lang(name, icon, color, version="$version"):
    return f'''[{name}]
format = " [$symbol{version}]($style)"
symbol = "{icon} "
style = "{color}"
'''


langs = "\n".join([
    lang("python", I["py"], "yellow", "$version( \\\\($virtualenv\\\\))"),
    lang("nodejs", I["node"], "green"), lang("bun", I["bun"], "pink"),
    lang("deno", I["deno"], "green"), lang("rust", I["rust"], "orange"),
    lang("golang", I["go"], "blue"), lang("java", I["java"], "red"),
    lang("kotlin", I["kotlin"], "violet"), lang("php", I["php"], "violet"),
    lang("c", I["c"], "blue", "($version)"), lang("lua", I["lua"], "blue"),
    lang("package", I["pkg"], "muted"),
]) + f'''
[cpp]
disabled = false
format = " [$symbol($version)]($style)"
symbol = "{I["cpp"]} "
style = "blue"

[docker_context]
format = " [$symbol$context]($style)"
symbol = "{I["docker"]} "
style = "blue"
'''

write(".config/starship.toml", f'''"$schema" = 'https://starship.rs/config-schema.json'
# Nocturne prompt — generated by nocturne/src/prompt.py (edit there, not here)

add_newline = true
command_timeout = 800
palette = "nocturne"

format = """
[{L}](mint)$os$username$hostname[{R}](fg:mint bg:mint_tint)$directory[{R}](fg:mint_tint)\\
( [{L}](fg:violet_tint)$git_branch$git_commit$git_state$git_status[{R}](fg:violet_tint))\\
$fill\\
$python$nodejs$bun$deno$rust$golang$java$kotlin$php$c$cpp$lua$docker_context$package\\
$cmd_duration $time
$status$jobs$sudo$character"""

[palettes.nocturne]
{palette}

[fill]
symbol = "·"
style = "border"

[os]
disabled = false
format = "[$symbol ]($style)"
style = "bg:mint fg:on_mint bold"
[os.symbols]
Arch = "{I["arch"]}"
Linux = "{I["linux"]}"

[username]
format = "[$user]($style)"
style_user = "bg:mint fg:on_mint bold"
style_root = "bg:red fg:crust bold"

[hostname]
ssh_only = true
format = "[@$hostname ]($style)"
style = "bg:mint fg:on_mint"

[directory]
format = "[ {I["dir"]}  $path ]($style)[$read_only]($read_only_style)"
style = "bg:mint_tint fg:mint bold"
read_only = "{I["lock"]} "
read_only_style = "bg:mint_tint fg:red"
truncation_length = 4
truncate_to_repo = true
truncation_symbol = "…/"
home_symbol = "~"

[git_branch]
format = "[ $symbol$branch(:$remote_branch) ]($style)"
symbol = "{I["branch"]} "
style = "bg:violet_tint fg:violet bold"

[git_commit]
tag_disabled = false
format = "[$hash$tag ]($style)"
style = "bg:violet_tint fg:violet"

[git_state]
format = "[$state( $progress_current/$progress_total) ]($style)"
style = "bg:violet_tint fg:orange bold"

[git_status]
format = "([$all_status$ahead_behind]($style))"
style = "bg:violet_tint fg:yellow"
conflicted = "=$count "
ahead = "⇡$count "
behind = "⇣$count "
diverged = "⇕⇡$ahead_count⇣$behind_count "
untracked = "?$count "
stashed = "≡$count "
modified = "!$count "
staged = "+$count "
renamed = "»$count "
deleted = "✘$count "

{langs}
[cmd_duration]
min_time = 2000
format = " [{I["hourglass"]} $duration]($style)"
style = "yellow"

[time]
disabled = false
format = "[{L}](surface2)[{I["clock"]} $time]($style)[{R}](surface2)"
style = "bg:surface2 fg:subtext"
time_format = "%-I:%M %p"

[status]
disabled = false
format = "[$symbol$status]($style) "
symbol = "✘ "
style = "bold red"
map_symbol = true
not_executable_symbol = "{I["noexec"]} "
not_found_symbol = "? "
sigint_symbol = "^C "
signal_symbol = "⚡"

[jobs]
format = "[$symbol$number]($style) "
symbol = "{I["jobs"]} "
style = "bold blue"

[sudo]
disabled = false
format = "[$symbol]($style)"
symbol = "{I["sudo"]} "
style = "bold orange"

[character]
success_symbol = "[❯](bold mint)"
error_symbol = "[❯](bold red)"
vimcmd_symbol = "[❮](bold violet)"
''')
